package com.mascotcapsule.micro3d.v3;

public final class Util3D {
    private Util3D() {
    }

    public static int sqrt(int value) {
        return com.jblend.graphics.j3d.Util3D.sqrt(value);
    }

    public static int sin(int angle) {
        return com.jblend.graphics.j3d.Util3D.sin(angle);
    }

    public static int cos(int angle) {
        return com.jblend.graphics.j3d.Util3D.cos(angle);
    }
}
