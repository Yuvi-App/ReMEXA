    public static int combinedLevel(int first, int second) {
        return COMBINED_VOLUME[Math.min(192, LOG_VOLUME[Math.clamp(first, 0, 127)] + LOG_VOLUME[Math.clamp(second, 0, 127)])];
    }

    public static int channelIndex(int volume, int expression) {
        return VOLUME_INDEX[combinedLevel(volume, expression) >> 2];
    }

    public static int channelLevel(int volume, int expression) { return LEVEL[channelIndex(volume,expression) >>> 16]; }

    public static int panIndex(int value, boolean right) {
        return (right ? PAN_RIGHT_INDEX : PAN_LEFT_INDEX)[Math.clamp(value, 0, 127) >> 2];
    }

    public static int noteLevel(int velocity, boolean legacyPcmBoost) {
        int attenuation = LOG_VOLUME[Math.clamp(velocity, 0, 127)] - (legacyPcmBoost ? 24 : 0);
        return NOTE_LEVEL[COMBINED_VOLUME[Math.max(0, attenuation)] >> 2];
    }

    public static int gain(int noteLevel, int channelLevel, int channelPanLevel,
                           int voicePan, boolean panEnabled, boolean mono, boolean right) {
        int gain = noteLevel * channelLevel >> 15;
        if (mono) return gain;
        int pan = panEnabled ? (right ? VOICE_PAN_RIGHT : VOICE_PAN_LEFT)[Math.clamp(voicePan, 0, 31)] : channelPanLevel;
        return gain * pan >> 15;
    }
